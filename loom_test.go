const testBotID = "U07BOT"

// === translate: Events API ==================================================

func mentionEvent(team, channel, user, text, ts, threadTS, botID string) socketmode.Event {
	return socketmode.Event{
		Type: socketmode.EventTypeEventsAPI,
		Data: slackevents.EventsAPIEvent{
			TeamID: team,
			InnerEvent: slackevents.EventsAPIInnerEvent{
				Data: &slackevents.AppMentionEvent{
					User:            user,
					Text:            text,
					TimeStamp:       ts,
					ThreadTimeStamp: threadTS,
					Channel:         channel,
					BotID:           botID,
				},
			},
		},
	}
}

func TestTranslate_Mention(t *testing.T) {
	evt := mentionEvent("T1", "C1", "U_ALICE", "<@U07BOT> deploy staging", "111.1", "", "")
	got, ok := translate(evt, testBotID)
	if !ok {
		t.Fatal("mention should be handled")
	}
	if got.Kind != KindMention {
		t.Errorf("Kind = %v, want mention", got.Kind)
	}
	if got.Text != "deploy staging" {
		t.Errorf("Text = %q, want %q (mention token should be stripped)", got.Text, "deploy staging")
	}
	if got.Context.Channel != "C1" || got.Context.User != "U_ALICE" || got.Context.Workspace != "T1" {
		t.Errorf("Context = %+v, want C1/U_ALICE/T1", got.Context)
	}
	if got.Timestamp != "111.1" {
		t.Errorf("Timestamp = %q, want 111.1", got.Timestamp)
	}
	if got.Context.Bot != testBotID {
		t.Errorf("Context.Bot = %q, want %q", got.Context.Bot, testBotID)
	}
}

