// === stripMention ==========================================================

func TestStripMention(t *testing.T) {
	cases := []struct{ in, want string }{
		{"<@U07BOT> deploy", "deploy"},
		{"<@U07BOT>   spaces", "spaces"},
		{"<@U07BOT>", ""},
		{"no mention here", "no mention here"},
		{"<@OTHER> keep", "<@OTHER> keep"},
	}
	for _, c := range cases {
		if got := stripMention(c.in, testBotID); got != c.want {
			t.Errorf("stripMention(%q) = %q, want %q", c.in, got, c.want)
		}
	}
}

// === EchoHandler ===========================================================

func TestEchoHandler_Mention(t *testing.T) {
	reply, err := EchoHandler(context.Background(), Event{
		Kind: KindMention,
		Text: "deploy staging",
	})
	if err != nil {
		t.Fatalf("EchoHandler: %v", err)
	}
	if reply.Text != "echo: deploy staging" {
		t.Errorf("Text = %q, want %q", reply.Text, "echo: deploy staging")
	}
	if len(reply.React) != 1 || reply.React[0] != "eyes" {
		t.Errorf("React = %v, want [eyes]", reply.React)
	}
	if reply.Target != TargetSameThread {
		t.Errorf("Target = %v, want SameThread", reply.Target)
	}
}

func TestEchoHandler_EmptyMention(t *testing.T) {
	reply, err := EchoHandler(context.Background(), Event{Kind: KindMention, Text: "   "})
	if err != nil {
		t.Fatalf("EchoHandler: %v", err)
	}
	if reply.Text != "" {
		t.Errorf("Text = %q, want empty (ack-only)", reply.Text)
	}
	if len(reply.React) != 1 {
		t.Errorf("React = %v, want one ack reaction", reply.React)
	}
}

func TestEchoHandler_SlashCommand(t *testing.T) {
	reply, err := EchoHandler(context.Background(), Event{Kind: KindSlashCommand, Text: "status"})
	if err != nil {
		t.Fatalf("EchoHandler: %v", err)
	}
	if reply.Target != TargetEphemeral {
		t.Errorf("Target = %v, want Ephemeral", reply.Target)
	}
	if reply.Text == "" {
		t.Error("slash command reply should have text")
	}
}

func TestEchoHandler_IgnoresOther(t *testing.T) {
	for _, k := range []EventKind{KindReaction, KindFileShared, KindInteraction} {
		reply, err := EchoHandler(context.Background(), Event{Kind: k})
		if err != nil {
			t.Fatalf("EchoHandler(%v): %v", k, err)
		}
		if !reply.IsEmpty() {
			t.Errorf("EchoHandler(%v) should return empty reply, got %+v", k, reply)
		}
	}
}

